"""Docs encyclopedia: picture galleries and the generated pages (no network; run after 50_materials.py, also by prepare.py).

- fills every block  <!-- gallery: rec:Porta Romana | event:… | map -->  …  <!-- /gallery -->  in docs/encyclopedia/*.md
  with the matching pictures of docs/materials/materials.json (thumbnail linking to the large image, caption, credit)
- writes docs/encyclopedia/maps-and-images.md (every picture, by topic) and docs/encyclopedia/events.md
  (the app's timeline events with their summaries, sources and pictures, read from web/src/data/history.ts)
"""
import os, re, json, html
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ENC, MAT = os.path.join(ROOT, "docs", "encyclopedia"), os.path.join(ROOT, "docs", "materials")
M = json.load(open(os.path.join(MAT, "materials.json"), encoding="utf-8"))
REPO = "https://github.com/Jany-M/firenze-story/blob/main/"

def figure(m):
    lic = f"[{m['license']}]({m['license_url']})" if m.get("license_url") else m["license"]
    src = f" · [source]({m['page']})" if m.get("page") else ""
    cap = html.escape(m["caption"]).replace("|", "&#124;"); alt = cap.replace("[", "(").replace("]", ")")
    author = html.escape(m["author"]).replace("|", "&#124;")
    # Absolute /materials/… so the library site (docs_dir = encyclopedia → /library/) and
    # the app share one picture store at web/public/materials (no /library/encyclopedia/ nesting).
    return (f'<figure markdown>\n[![{alt}](/materials/{m["thumb"]})](/materials/{m["img"]})\n'
            f'<figcaption markdown>{cap}<br><small>{author}{" · " + html.escape(m["date"]) if m.get("date") else ""} · {lic}{src}</small></figcaption>\n</figure>\n')
def gallery(ms):
    return '<div class="mgallery" markdown>\n\n' + "\n".join(figure(m) for m in ms) + '\n</div>\n' if ms else "*No pictures yet.*\n"
def select(subjects):
    out = []
    for m in M:
        keys = set(m["subjects"]) | ({"map:circles"} if m["src_file"].endswith("circles-of-walls.jpg") else set())
        if keys & set(subjects) and m not in out: out.append(m)
    return out

# 1. gallery blocks in the hand-written entries
BLOCK = re.compile(r"<!-- gallery: (.*?) -->.*?<!-- /gallery -->", re.S)
for f in sorted(os.listdir(ENC)):
    if not f.endswith(".md") or f in ("maps-and-images.md", "events.md"): continue
    p = os.path.join(ENC, f); s = open(p, encoding="utf-8").read()
    t = BLOCK.sub(lambda mo: f"<!-- gallery: {mo.group(1)} -->\n{gallery(select([x.strip() for x in mo.group(1).split('|')]))}<!-- /gallery -->", s)
    if t != s: open(p, "w", encoding="utf-8", newline="\n").write(t); print("galleries:", f)

# 2. every picture, by topic
TOPICS = [("maps", "Maps and views of the city"), ("walls", "Walls, gates and towers"), ("landmarks", "Landmarks"), ("history", "History and events")]
out = ["<!-- Generated by pipeline/52_encyclopedia.py from docs/materials/materials.json – edit the manifest, not this page. -->\n",
       "# Maps and images\n", f"All {len(M)} pictures in the collection. Click a picture to open it large. Each one keeps its author, licence and "
       "source page; the list is `docs/materials/manifest.json`.\n"]
for k, title in TOPICS:
    ms = [m for m in M if m["topic"] == k]
    if ms: out += [f"## {title}\n", gallery(ms)]
open(os.path.join(ENC, "maps-and-images.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))

# 3. events, from the app's data
H = open(os.path.join(ROOT, "web", "src", "data", "history.ts"), encoding="utf-8").read()
Q = r"'((?:\\'|[^'])*)'"
unq = lambda s: s.replace("\\'", "'")
events = [(int(m.group(1)), m.group(2) and unq(m.group(2)), unq(m.group(3)), unq(m.group(4)))
          for m in re.finditer(r"\{ year: (-?\d+),(?: date: '([^']*)',)?(?: hour: [\d.]+,)? title: " + Q + r", place: " + Q, H)]
consts = {"HIST": REPO + "docs/HISTORY.md"}
refs = {}
for m in re.finditer(r"\n  " + Q + r": \{ sum: " + Q + r",\s*src: \[(.*?)\]\],?\s*(?:wiki: (W\('([^']*)'\)|'([^']*)'))?", H, re.S):
    srcs = []
    for s in re.finditer(r"\[" + Q + r",\s*([^\]]+?)\]", m.group(3) + "]"):
        u = s.group(2).strip(); u = unq(u[1:-1]) if u.startswith("'") else consts.get(u, "")
        srcs.append((unq(s.group(1)), u))
    wiki = ("https://it.wikipedia.org/wiki/" + m.group(5)) if m.group(5) else (m.group(6) or "")
    refs[unq(m.group(1))] = (unq(m.group(2)), srcs, wiki)
MON = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]
fy = lambda y: f"{-y} BC" if y < 0 else str(y)
out = ["<!-- Generated by pipeline/52_encyclopedia.py from web/src/data/history.ts – edit the app's data, not this page. -->\n",
       "# Events\n", "The events on the app's timeline. In the app, click a dot on the timeline or an event in the Live list: "
       "the camera flies there and the event card opens.\n"]
for y, d, t, place in events:
    r = refs.get(t); day = f"{int(d[3:])} {MON[int(d[:2]) - 1]} " if d else ""
    out.append(f"## {day}{fy(y)} · {t}\n")
    out.append(f"*{place}*\n")
    if r:
        out.append(r[0] + "\n")
        if r[1]: out.append("Sources: " + "; ".join(f"[{a}]({u})" if u else a for a, u in r[1]) + (f"; [Wikipedia]({r[2]})" if r[2] else "") + "\n")
    ms = select([f"event:{t}"])
    if ms: out.append(gallery(ms))
open(os.path.join(ENC, "events.md"), "w", encoding="utf-8", newline="\n").write("\n".join(out))
print(f"maps-and-images: {len(M)} pictures; events: {len(events)} ({sum(t in refs for _, _, t, _ in events)} with summaries)")
